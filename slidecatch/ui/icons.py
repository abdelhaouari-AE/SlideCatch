# Icons drawn filled instead of outlined.
FILLED = {"pause", "play", "stop"}

_cache = {}


def _svg(name: str, color: str) -> bytes:
    body = PATHS[name]
    if name in FILLED:
        attrs = 'fill="%s" stroke="none"' % color
    else:
        attrs = ('fill="none" stroke="%s" stroke-width="1.75" stroke-linecap="round" '
                 'stroke-linejoin="round"' % color)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" %s>%s</svg>'
            % (attrs, body)).encode()


# Icons that point in a reading direction ("back", "move earlier", undo...).
# In Arabic they are drawn mirrored, as the whole interface is.
MIRRORED = {"back", "undo", "redo", "arrow_left", "arrow_right", "external"}


def pixmap(name: str, color: str, size: int = 18, ratio: float = 2.0) -> QPixmap:
    mirror = name in MIRRORED and is_rtl()
    key = (name, color, size, ratio, mirror)
    pm = _cache.get(key)
    if pm is None:
        renderer = QSvgRenderer(QByteArray(_svg(name, color)))
        side = int(size * ratio)
        pm = QPixmap(side, side)
        pm.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pm)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        if mirror:
            painter.translate(side, 0)
            painter.scale(-1, 1)
        renderer.render(painter, QRectF(0, 0, side, side))
        painter.end()
        pm.setDevicePixelRatio(ratio)
        _cache[key] = pm
    return pm


def icon(name: str, color: str, size: int = 18, disabled_color: str = None) -> QIcon:
    result = QIcon()
    result.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal)
    if disabled_color:
        result.addPixmap(pixmap(name, disabled_color, size), QIcon.Mode.Disabled)
    return result


def icon_size(size: int = 18) -> QSize:
    return QSize(size, size)
